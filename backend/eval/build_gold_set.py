def build() -> list[dict]:
    records: list[dict] = []
    for doc, payload in DOCS.items():
        for index, (intent, question, keywords) in enumerate(payload["items"], start=1):
            records.append(
                {
                    "id": f"{payload['slug']}_{index:02d}",
                    "doc": doc,
                    "question": question,
                    "intent": intent,
                    "expected_keywords": keywords,
                    "answerable": True,
                }
            )
    for index, question in enumerate(OUT_OF_SCOPE, start=1):
        records.append(
            {
                "id": f"oos_{index:02d}",
                "doc": "高龄老人津贴申领指南",
                "question": question,
                "intent": "out_of_scope",
                "expected_keywords": [],
                "answerable": False,
            }
        )
    return records


